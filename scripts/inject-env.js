// Injects environment variables from .env and Netlify process.env into js/env.js
// Zero-dependency pure Node.js script for Netlify build and local dev

const fs = require("fs");
const path = require("path");

const envVars = {};

// Client-safe public variables for Firebase (never include emails, passwords or secrets)
const targetKeys = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID"
];

// Parse .env file if it exists locally (strictly only for targetKeys)
const envPath = path.resolve(__dirname, "../.env");
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, "utf8");
  content.split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) return;
    const idx = trimmed.indexOf("=");
    if (idx !== -1) {
      const key = trimmed.slice(0, idx).trim();
      let val = trimmed.slice(idx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (targetKeys.includes(key)) {
        envVars[key] = val;
      }
    }
  });
}

// Override with process.env (Netlify Environment Variables take priority)
targetKeys.forEach((key) => {
  if (process.env[key]) {
    envVars[key] = process.env[key];
  }
});

const outDir = path.resolve(__dirname, "../js");
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

const outContent = `// Auto-generated by scripts/inject-env.js - DO NOT COMMIT TO VERSION CONTROL
window.__ENV__ = ${JSON.stringify(envVars, null, 2)};
`;

fs.writeFileSync(path.join(outDir, "env.js"), outContent, "utf8");
console.log("Successfully generated js/env.js with", Object.keys(envVars).length, "environment variables.");

